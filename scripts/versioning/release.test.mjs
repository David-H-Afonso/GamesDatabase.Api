import test from 'node:test';
import assert from 'node:assert/strict';
import { findReleaseNotes, releaseCreateArguments } from './release.mjs';
import { resolve } from 'node:path';

const identity = { repository: 'owner/project', tag: '2.1.0', sha: 'a'.repeat(40), title: 'Product 2.1.0' };
test('release identity still targets the exact tested commit and immutable tag', () => {
  const args = releaseCreateArguments(identity);
  assert.deepEqual(args.slice(0, 9), ['release', 'create', '2.1.0', '--repo', 'owner/project', '--target', identity.sha, '--title', 'Product 2.1.0']);
});
test('a prepared human release note replaces autogenerated git notes', () => {
  const args = releaseCreateArguments({ ...identity, notesFile: '/workspace/docs/releases/2.1.0.md' });
  assert.deepEqual(args.slice(-2), ['--notes-file', '/workspace/docs/releases/2.1.0.md']);
  assert.ok(!args.includes('--generate-notes'));
});
test('legacy versions without a prepared note retain generated notes', () => {
  assert.equal(releaseCreateArguments(identity).at(-1), '--generate-notes');
});
test('notes with spaces stay a single argument without shell interpolation', () => {
  const path = 'C:/private review/docs/releases/2.1.0.md';
  assert.equal(releaseCreateArguments({ ...identity, notesFile: path }).at(-1), path);
});
test('public notes are resolved for lowercase Front and uppercase API directories on Linux', () => {
  for (const directory of ['docs/releases', 'DOCS/releases']) {
    const target = resolve('/fixture', directory, '3.0.0.md');
    assert.equal(findReleaseNotes('/fixture', '3.0.0', path => path === target).path, target);
  }
  assert.equal(findReleaseNotes('/fixture', '3.0.0', () => false), undefined);
  assert.throws(() => findReleaseNotes('/fixture', '../../.env', () => true));
});
